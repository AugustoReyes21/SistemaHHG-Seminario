-- Seminario de TI · Aporte 1: idempotencia en el registro de ventas.
-- Guarda cada Idempotency-Key recibida para que un reintento de la misma
-- venta (doble clic, corte de red, recarga) no cree una segunda venta.
CREATE TABLE IF NOT EXISTS idempotency_keys (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope           VARCHAR(120) NOT NULL,          -- operación protegida, p. ej. 'POST /api/register_sale'
    user_id         BIGINT       NOT NULL,          -- la llave es única por usuario
    idem_key        VARCHAR(100) NOT NULL,          -- valor del encabezado Idempotency-Key
    request_hash    CHAR(64)     NOT NULL,          -- SHA-256 del cuerpo canónico
    status          VARCHAR(20)  NOT NULL DEFAULT 'processing',
    resource_id     BIGINT       NULL,              -- venta creada (se fija dentro de la transacción)
    response_status INT          NULL,
    response_body   JSONB        NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP    NOT NULL DEFAULT NOW(),
    expires_at      TIMESTAMP    NOT NULL,
    CONSTRAINT uq_idempotency_scope_user_key UNIQUE (scope, user_id, idem_key),
    CONSTRAINT ck_idempotency_status CHECK (status IN ('processing', 'committed', 'completed')),
    CONSTRAINT fk_idempotency_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_idempotency_expires ON idempotency_keys (expires_at);
