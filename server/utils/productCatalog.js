const { query, tableExists, columnExists } = require('../db');
const { productStocksAvailable, getBranchStock } = require('../functions');

const PRODUCT_TYPES = Object.freeze({
  MEDICAMENTO: 'medicamento',
  SERVICIO: 'servicio',
  COMBO: 'combo'
});

function normalizeProductType(value) {
  const raw = String(value || '')
    .trim()
    .toLowerCase();
  if (raw === 'servicio' || raw === 'service') return PRODUCT_TYPES.SERVICIO;
  if (raw === 'combo' || raw === 'kit' || raw === 'paquete') return PRODUCT_TYPES.COMBO;
  return PRODUCT_TYPES.MEDICAMENTO;
}

function productTypeUsesInventory(value) {
  return normalizeProductType(value) === PRODUCT_TYPES.MEDICAMENTO;
}

function productTypeIsService(value) {
  return normalizeProductType(value) === PRODUCT_TYPES.SERVICIO;
}

function productTypeIsCombo(value) {
  return normalizeProductType(value) === PRODUCT_TYPES.COMBO;
}

async function ensureProductTypeColumn(db) {
  if (!(await tableExists(db, 'productos'))) return false;
  if (!(await columnExists(db, 'productos', 'tipo'))) {
    try {
      await query("ALTER TABLE productos ADD COLUMN tipo VARCHAR(20) DEFAULT 'medicamento'", [], db);
    } catch (_) {}
  }
  try {
    await query(
      "UPDATE productos SET tipo = 'medicamento' WHERE tipo IS NULL OR TRIM(COALESCE(tipo, '')) = ''",
      [],
      db
    );
  } catch (_) {}
  return await columnExists(db, 'productos', 'tipo');
}

async function ensureComboItemsTable(db) {
  try {
    await query(
      `CREATE TABLE IF NOT EXISTS product_combo_items (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        combo_product_id BIGINT NOT NULL,
        component_product_id BIGINT NOT NULL,
        quantity NUMERIC(12,2) NOT NULL DEFAULT 0,
        created_at TIMESTAMP NOT NULL DEFAULT NOW(),
        CONSTRAINT fk_combo_items_combo_product FOREIGN KEY (combo_product_id) REFERENCES productos(id),
        CONSTRAINT fk_combo_items_component_product FOREIGN KEY (component_product_id) REFERENCES productos(id)
      )`,
      [],
      db
    );
  } catch (_) {}
  try {
    await query(
      'CREATE UNIQUE INDEX IF NOT EXISTS idx_product_combo_items_unique ON product_combo_items (combo_product_id, component_product_id)',
      [],
      db
    );
  } catch (_) {}
  try {
    await query(
      'CREATE INDEX IF NOT EXISTS idx_product_combo_items_combo_product ON product_combo_items (combo_product_id)',
      [],
      db
    );
  } catch (_) {}
  try {
    await query(
      'CREATE INDEX IF NOT EXISTS idx_product_combo_items_component_product ON product_combo_items (component_product_id)',
      [],
      db
    );
  } catch (_) {}
  return await tableExists(db, 'product_combo_items');
}

async function ensureLotSaleProductColumn(db) {
  if (!(await tableExists(db, 'lot_sales'))) return false;
  if (!(await columnExists(db, 'lot_sales', 'sale_product_id'))) {
    try {
      await query('ALTER TABLE lot_sales ADD COLUMN sale_product_id BIGINT NULL', [], db);
    } catch (_) {}
  }
  return await columnExists(db, 'lot_sales', 'sale_product_id');
}

function normalizeComboComponents(list) {
  const merged = new Map();
  for (const raw of Array.isArray(list) ? list : []) {
    const componentProductId = Number(
      raw?.component_product_id ?? raw?.product_id ?? raw?.producto_id ?? raw?.id ?? 0
    );
    const quantity = Number(raw?.quantity ?? raw?.cantidad ?? 0);
    if (!componentProductId || !Number.isFinite(quantity) || quantity <= 0) continue;
    merged.set(componentProductId, Number((Number(merged.get(componentProductId) || 0) + quantity).toFixed(2)));
  }
  return Array.from(merged.entries())
    .map(([component_product_id, quantity]) => ({
      component_product_id: Number(component_product_id),
      quantity: Number(quantity)
    }))
    .sort((a, b) => a.component_product_id - b.component_product_id);
}

async function fetchComboComponents(db, comboIds = []) {
  const ids = Array.from(new Set((comboIds || []).map((value) => Number(value || 0)).filter(Boolean)));
  const out = new Map();
  if (!ids.length) return out;
  await ensureProductTypeColumn(db);
  await ensureComboItemsTable(db);
  const st = await query(
    `SELECT c.combo_product_id, c.component_product_id, c.quantity,
            p.nombre_comercial AS component_name,
            COALESCE(p.tipo, 'medicamento') AS component_type
       FROM product_combo_items c
       LEFT JOIN productos p ON p.id = c.component_product_id
      WHERE c.combo_product_id = ANY($1)
      ORDER BY c.combo_product_id ASC, c.id ASC`,
    [ids],
    db
  );
  for (const row of st.rows || []) {
    const comboId = Number(row.combo_product_id || 0);
    if (!comboId) continue;
    if (!out.has(comboId)) out.set(comboId, []);
    out.get(comboId).push({
      component_product_id: Number(row.component_product_id || 0),
      quantity: Number(row.quantity || 0),
      nombre_comercial: String(row.component_name || '').trim(),
      tipo: normalizeProductType(row.component_type)
    });
  }
  return out;
}

async function replaceComboComponents(db, comboProductId, components) {
  await ensureComboItemsTable(db);
  const comboId = Number(comboProductId || 0);
  if (!comboId) return;
  const normalized = normalizeComboComponents(components);
  await query('DELETE FROM product_combo_items WHERE combo_product_id = $1', [comboId], db);
  for (const component of normalized) {
    await query(
      'INSERT INTO product_combo_items (combo_product_id, component_product_id, quantity) VALUES ($1,$2,$3)',
      [comboId, component.component_product_id, component.quantity],
      db
    );
  }
}

async function fetchProductTypeMap(db, productIds = []) {
  const ids = Array.from(new Set((productIds || []).map((value) => Number(value || 0)).filter(Boolean)));
  const out = new Map();
  if (!ids.length) return out;
  await ensureProductTypeColumn(db);
  const st = await query(
    "SELECT id, COALESCE(tipo, 'medicamento') AS tipo FROM productos WHERE id = ANY($1)",
    [ids],
    db
  );
  for (const row of st.rows || []) {
    out.set(Number(row.id || 0), normalizeProductType(row.tipo));
  }
  return out;
}

async function ensureAvailabilityCache(db, cache = {}) {
  if (cache.hasLots == null) cache.hasLots = await tableExists(db, 'lots');
  if (cache.hasStockTable == null) cache.hasStockTable = await productStocksAvailable(db);
  if (!cache.qtyByKey) cache.qtyByKey = new Map();
  return cache;
}

async function getAvailableComponentQty(db, productId, branchId = null, cache = {}) {
  const pid = Number(productId || 0);
  if (!pid) return 0;
  await ensureAvailabilityCache(db, cache);
  const key = `${branchId || 'all'}:${pid}`;
  if (cache.qtyByKey.has(key)) return cache.qtyByKey.get(key);

  let available = 0;
  if (cache.hasLots) {
    if (branchId) {
      const st = await query(
        `SELECT COALESCE(SUM(quantity),0) AS qty
           FROM lots
          WHERE product_id = $1
            AND branch_id = $2
            AND quantity > 0
            AND expiry_date IS NOT NULL
            AND expiry_date >= CURRENT_DATE`,
        [pid, branchId],
        db
      );
      available = Number(st.rows[0]?.qty || 0);
    } else {
      const st = await query(
        `SELECT COALESCE(SUM(quantity),0) AS qty
           FROM lots
          WHERE product_id = $1
            AND quantity > 0
            AND expiry_date IS NOT NULL
            AND expiry_date >= CURRENT_DATE`,
        [pid],
        db
      );
      available = Number(st.rows[0]?.qty || 0);
    }
  } else if (branchId) {
    available = cache.hasStockTable ? await getBranchStock(db, pid, branchId) : 0;
    if (!cache.hasStockTable) {
      const st = await query('SELECT stock FROM productos WHERE id = $1', [pid], db);
      available = Number(st.rows[0]?.stock || 0);
    }
  } else if (cache.hasStockTable) {
    const st = await query('SELECT COALESCE(SUM(stock),0) AS qty FROM product_stocks WHERE product_id = $1', [pid], db);
    available = Number(st.rows[0]?.qty || 0);
  } else {
    const st = await query('SELECT stock FROM productos WHERE id = $1', [pid], db);
    available = Number(st.rows[0]?.stock || 0);
  }

  const normalized = Number.isFinite(available) ? Math.max(0, available) : 0;
  cache.qtyByKey.set(key, normalized);
  return normalized;
}

async function computeComboAvailability(db, components, branchId = null, cache = {}) {
  const normalized = normalizeComboComponents(components);
  if (!normalized.length) return { stock: 0, stock_total: 0, missing_components: [] };

  const componentMeta = new Map();
  for (const raw of Array.isArray(components) ? components : []) {
    const componentProductId = Number(
      raw?.component_product_id ?? raw?.product_id ?? raw?.producto_id ?? raw?.id ?? 0
    );
    if (!componentProductId || componentMeta.has(componentProductId)) continue;
    componentMeta.set(componentProductId, {
      nombre_comercial: String(raw?.nombre_comercial || raw?.component_name || '').trim(),
      tipo: raw?.tipo != null ? normalizeProductType(raw.tipo) : null
    });
  }

  const typeMap = await fetchProductTypeMap(
    db,
    normalized.map((component) => component.component_product_id)
  );
  const trackedComponents = normalized.filter((component) => {
    const metaType = componentMeta.get(component.component_product_id)?.tipo;
    const componentType = metaType || typeMap.get(component.component_product_id);
    return productTypeUsesInventory(componentType);
  });
  if (!trackedComponents.length) {
    return { stock: 0, stock_total: 0, missing_components: [] };
  }

  let stock = branchId ? Number.POSITIVE_INFINITY : 0;
  let stockTotal = Number.POSITIVE_INFINITY;
  const missingComponents = new Set();

  for (const component of trackedComponents) {
    const totalAvailable = await getAvailableComponentQty(db, component.component_product_id, null, cache);
    const totalCombos = Math.floor(totalAvailable / Number(component.quantity || 1));
    stockTotal = Math.min(stockTotal, totalCombos);
    const componentName =
      componentMeta.get(component.component_product_id)?.nombre_comercial ||
      `Producto ${component.component_product_id}`;

    if (branchId) {
      const branchAvailable = await getAvailableComponentQty(db, component.component_product_id, branchId, cache);
      const branchCombos = Math.floor(branchAvailable / Number(component.quantity || 1));
      stock = Math.min(stock, branchCombos);
      if (branchAvailable < Number(component.quantity || 1)) {
        missingComponents.add(componentName);
      }
    } else if (totalAvailable < Number(component.quantity || 1)) {
      missingComponents.add(componentName);
    }
  }

  const finalTotal = Number.isFinite(stockTotal) ? Math.max(0, stockTotal) : 0;
  const finalStock = branchId
    ? Number.isFinite(stock)
      ? Math.max(0, stock)
      : 0
    : finalTotal;

  return {
    stock: finalStock,
    stock_total: finalTotal,
    missing_components: Array.from(missingComponents)
  };
}

