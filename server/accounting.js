const { query, withTransaction } = require('./db');
const { branchNameCached } = require('./functions');

let accountingSchemaPromise = null;
let accountingSchemaReady = false;

async function ensureAccountingSchema() {
  if (accountingSchemaReady) return;
  if (accountingSchemaPromise) return accountingSchemaPromise;
  accountingSchemaPromise = (async () => {
    await query(`
      CREATE TABLE IF NOT EXISTS accounts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        code VARCHAR(50) NOT NULL UNIQUE,
        name VARCHAR(200) NOT NULL,
        type VARCHAR(50) NOT NULL,
        level INT NOT NULL DEFAULT 1,
        parent_id BIGINT NULL,
        currency VARCHAR(10) NOT NULL DEFAULT 'GTQ',
        active BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TIMESTAMP NOT NULL DEFAULT NOW(),
        CONSTRAINT fk_accounts_parent FOREIGN KEY (parent_id) REFERENCES accounts(id) ON DELETE SET NULL
      )
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS journal_entries (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        fecha TIMESTAMP NOT NULL,
        descripcion TEXT,
        usuario_id BIGINT NULL,
        origen VARCHAR(50),
        origen_id BIGINT NULL,
        total_debe NUMERIC(14,2) NOT NULL DEFAULT 0,
        total_haber NUMERIC(14,2) NOT NULL DEFAULT 0,
        estado VARCHAR(20) DEFAULT 'activo',
        created_at TIMESTAMP NOT NULL DEFAULT NOW(),
        CONSTRAINT fk_journal_entries_user FOREIGN KEY (usuario_id) REFERENCES users(id)
      )
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS journal_lines (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        entry_id BIGINT NOT NULL,
        account_id BIGINT NOT NULL,
        descripcion TEXT,
        debe NUMERIC(14,2) NOT NULL DEFAULT 0,
        haber NUMERIC(14,2) NOT NULL DEFAULT 0,
        branch_id BIGINT NULL,
        producto_id BIGINT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT NOW(),
        CONSTRAINT fk_journal_lines_entry FOREIGN KEY (entry_id) REFERENCES journal_entries(id) ON DELETE CASCADE,
        CONSTRAINT fk_journal_lines_account FOREIGN KEY (account_id) REFERENCES accounts(id),
        CONSTRAINT fk_journal_lines_branch FOREIGN KEY (branch_id) REFERENCES branches(id),
        CONSTRAINT fk_journal_lines_product FOREIGN KEY (producto_id) REFERENCES productos(id)
      )
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS bank_accounts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(120) NOT NULL,
        bank VARCHAR(120),
        number VARCHAR(80),
        currency VARCHAR(10) DEFAULT 'GTQ',
        saldo_inicial NUMERIC(14,2) NOT NULL DEFAULT 0,
        branch_id BIGINT NULL,
        account_id BIGINT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT NOW(),
        CONSTRAINT fk_bank_accounts_branch FOREIGN KEY (branch_id) REFERENCES branches(id),
        CONSTRAINT fk_bank_accounts_account FOREIGN KEY (account_id) REFERENCES accounts(id)
      )
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS bank_movements (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        bank_account_id BIGINT NOT NULL,
        fecha DATE NOT NULL,
        tipo VARCHAR(30) NOT NULL,
        monto NUMERIC(14,2) NOT NULL DEFAULT 0,
        referencia VARCHAR(120),
        contracuenta_id BIGINT NULL,
        journal_entry_id BIGINT NULL,
        conciliado BOOLEAN NOT NULL DEFAULT FALSE,
        created_at TIMESTAMP NOT NULL DEFAULT NOW(),
        CONSTRAINT fk_bank_movements_account FOREIGN KEY (bank_account_id) REFERENCES bank_accounts(id) ON DELETE CASCADE,
        CONSTRAINT fk_bank_movements_contra FOREIGN KEY (contracuenta_id) REFERENCES accounts(id),
        CONSTRAINT fk_bank_movements_journal FOREIGN KEY (journal_entry_id) REFERENCES journal_entries(id)
      )
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS bank_reconciliations (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        bank_account_id BIGINT NOT NULL,
        periodo_inicio DATE NOT NULL,
        periodo_fin DATE NOT NULL,
        saldo_extracto NUMERIC(14,2) NOT NULL DEFAULT 0,
        saldo_libros NUMERIC(14,2) NOT NULL DEFAULT 0,
        diferencia NUMERIC(14,2) NOT NULL DEFAULT 0,
        created_at TIMESTAMP NOT NULL DEFAULT NOW(),
        CONSTRAINT fk_bank_reconciliations_account FOREIGN KEY (bank_account_id) REFERENCES bank_accounts(id) ON DELETE CASCADE
      )
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS bank_reconciliation_items (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        reconciliation_id BIGINT NOT NULL,
        bank_movement_id BIGINT NOT NULL,
        estado VARCHAR(30) NOT NULL DEFAULT 'conciliado',
        nota TEXT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT NOW(),
        CONSTRAINT fk_bank_reconciliation_items_recon FOREIGN KEY (reconciliation_id) REFERENCES bank_reconciliations(id) ON DELETE CASCADE,
        CONSTRAINT fk_bank_reconciliation_items_movement FOREIGN KEY (bank_movement_id) REFERENCES bank_movements(id) ON DELETE CASCADE
      )
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS checks (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        purchase_id BIGINT NULL,
        bank_account_id BIGINT NOT NULL,
        account_id BIGINT NOT NULL,
        branch_id BIGINT NULL,
        amount NUMERIC(14,2) NOT NULL DEFAULT 0,
        issue_date DATE NOT NULL,
        check_number BIGINT NOT NULL,
        pay_to VARCHAR(200),
        note TEXT,
        status VARCHAR(30) NOT NULL DEFAULT 'emitido',
        created_by BIGINT NULL,
        journal_entry_id BIGINT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT NOW(),
        CONSTRAINT fk_checks_purchase FOREIGN KEY (purchase_id) REFERENCES purchases(id),
        CONSTRAINT fk_checks_bank_account FOREIGN KEY (bank_account_id) REFERENCES bank_accounts(id),
        CONSTRAINT fk_checks_account FOREIGN KEY (account_id) REFERENCES accounts(id),
        CONSTRAINT fk_checks_branch FOREIGN KEY (branch_id) REFERENCES branches(id),
        CONSTRAINT fk_checks_created_by FOREIGN KEY (created_by) REFERENCES users(id),
        CONSTRAINT fk_checks_journal FOREIGN KEY (journal_entry_id) REFERENCES journal_entries(id)
      )
    `);
  })();

  try {
    await accountingSchemaPromise;
    accountingSchemaReady = true;
  } catch (err) {
    accountingSchemaPromise = null;
    throw err;
  }
}

async function ensureAccount(db, code, name, type, level = 1, currency = 'GTQ') {
  await ensureAccountingSchema();
  const res = await query('SELECT id FROM accounts WHERE code = $1 LIMIT 1', [code], db);
  if (res.rows[0]) return Number(res.rows[0].id);
  const ins = await query(
    'INSERT INTO accounts (code, name, type, level, currency, active) VALUES ($1,$2,$3,$4,$5,TRUE) RETURNING id',
    [code, name, type, level, currency],
    db
  );
  return Number(ins.rows[0].id);
}

let defaultAccountsCache = null;

async function ensureDefaultAccounts(db) {
  await ensureAccountingSchema();
  if (defaultAccountsCache) return defaultAccountsCache;
  const defaults = {
    cash: ['1101', 'Caja general', 'activo'],
    bank: ['1102', 'Banco general', 'activo'],
    inventory: ['1201', 'Inventario de mercaderias', 'activo'],
    payables: ['2101', 'Cuentas por pagar a proveedores', 'pasivo'],
    receivable: ['1301', 'Cuentas por cobrar clientes', 'activo'],
    sales: ['4101', 'Ingresos por ventas', 'ingreso']
  };
  const out = {};
  for (const key of Object.keys(defaults)) {
    const [code, name, type] = defaults[key];
    out[key] = await ensureAccount(db, code, name, type);
  }
  defaultAccountsCache = out;
  return out;
}

async function existingEntryForOrigin(db, origin, originId) {
  await ensureAccountingSchema();
  const res = await query(
    'SELECT id FROM journal_entries WHERE origen = $1 AND origen_id = $2 LIMIT 1',
    [origin, originId],
    db
  );
  return res.rows[0] ? Number(res.rows[0].id) : null;
}

async function createJournalEntryWithLines(db, fecha, descripcion, lines, origin = null, originId = null, usuarioId = null) {
  await ensureAccountingSchema();
  if (!Array.isArray(lines) || lines.length === 0) {
    throw new Error('lines requeridas');
  }
  let totalDebe = 0;
  let totalHaber = 0;
  for (const ln of lines) {
    const accId = Number(ln.account_id || 0);
    if (!accId) throw new Error('account_id invalido');
    const debe = Number(ln.debe || 0);
    const haber = Number(ln.haber || 0);
    totalDebe += debe;
    totalHaber += haber;
  }
  if (Number(totalDebe.toFixed(2)) !== Number(totalHaber.toFixed(2))) {
    throw new Error('La partida no cuadra (debe/haber)');
  }

  const run = async (client) => {
    const ins = await query(
      'INSERT INTO journal_entries (fecha, descripcion, usuario_id, origen, origen_id, total_debe, total_haber) VALUES ($1,$2,$3,$4,$5,$6,$7) RETURNING id',
      [fecha, descripcion, usuarioId, origin, originId, totalDebe, totalHaber],
      client
    );
    const entryId = Number(ins.rows[0].id);

    for (const ln of lines) {
      await query(
        'INSERT INTO journal_lines (entry_id, account_id, descripcion, debe, haber, branch_id, producto_id) VALUES ($1,$2,$3,$4,$5,$6,$7)',
        [
          entryId,
          Number(ln.account_id),
          ln.descripcion || null,
          Number(ln.debe || 0),
          Number(ln.haber || 0),
          ln.branch_id != null ? Number(ln.branch_id) : null,
          ln.producto_id != null ? Number(ln.producto_id) : null
        ],
        client
      );
    }
    return entryId;
  };

  if (db) {
    return run(db);
  }
  return withTransaction(run);
}

async function autoEntryForCashClose(db, monto, branchId, cierreId, usuarioId = null) {
  const amount = Number(monto || 0);
  if (amount <= 0) return null;
  if (cierreId) {
    const existing = await existingEntryForOrigin(db, 'cierre_caja', cierreId);
    if (existing) return existing;
  }
  const defs = await ensureDefaultAccounts(db);
  const branchName = branchId ? await branchNameCached(db, branchId) : '';
  const desc = `Ingreso diario caja${branchName ? ` (${branchName})` : ''}`;
  const lines = [
    {
      account_id: defs.cash,
      descripcion: 'Efectivo de cierre de caja',
      debe: amount,
      haber: 0,
      branch_id: branchId
    },
    {
      account_id: defs.sales,
      descripcion: 'Ventas del dia',
      debe: 0,
      haber: amount,
      branch_id: branchId
    }
  ];
  const fecha = new Date().toISOString().slice(0, 10);
  return createJournalEntryWithLines(db, fecha, desc, lines, 'cierre_caja', cierreId, usuarioId);
}

function normalizeToken(value) {
  return String(value || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

async function autoEntryForPurchase(db, purchaseId, total, branchId, paymentType, paymentForm, usuarioId = null, fecha = null) {
  const amount = Number(total || 0);
  if (purchaseId <= 0 || amount <= 0) return null;
  const existing = await existingEntryForOrigin(db, 'compra', purchaseId);
  if (existing) return existing;
  const defs = await ensureDefaultAccounts(db);
  const payType = normalizeToken(paymentType);
  const payForm = normalizeToken(paymentForm);
  let creditAccount = defs.payables;
  if (payType !== 'credito') {
    creditAccount = payForm === 'efectivo' ? defs.cash : defs.bank;
  }
  const branchName = branchId ? await branchNameCached(db, branchId) : '';
  const desc = `Compra #${purchaseId}${branchName ? ` sucursal ${branchName}` : ''}`;
  const lines = [
    {
      account_id: defs.inventory,
      descripcion: 'Inventario por compra',
      debe: amount,
      haber: 0,
      branch_id: branchId
    },
    {
      account_id: creditAccount,
      descripcion: 'Obligacion de compra',
      debe: 0,
      haber: amount,
      branch_id: branchId
    }
  ];
  const date = fecha || new Date().toISOString().slice(0, 10);
  return createJournalEntryWithLines(db, date, desc, lines, 'compra', purchaseId, usuarioId);
}

async function autoEntryForSale(db, saleId, total, branchId, paymentMethod, paymentTerms, usuarioId = null, fecha = null) {
  const amount = Number(total || 0);
  if (saleId <= 0 || amount <= 0) return null;
  const existing = await existingEntryForOrigin(db, 'venta', saleId);
  if (existing) return existing;
  const defs = await ensureDefaultAccounts(db);
  const method = normalizeToken(paymentMethod);
  const terms = normalizeToken(paymentTerms);
  let debitAcc = defs.cash;
  if (terms === 'credito') {
    debitAcc = defs.receivable;
  } else if (['tarjeta', 'transferencia', 'banco'].includes(method)) {
    debitAcc = defs.bank;
  }
  const branchName = branchId ? await branchNameCached(db, branchId) : '';
  const desc = `Venta #${saleId}${branchName ? ` sucursal ${branchName}` : ''}`;
  const lines = [
    {
      account_id: debitAcc,
      descripcion: 'Cobro de venta',
      debe: amount,
      haber: 0,
      branch_id: branchId
    },
    {
      account_id: defs.sales,
      descripcion: 'Ingreso por venta',
      debe: 0,
      haber: amount,
      branch_id: branchId
    }
  ];
  const date = fecha || new Date().toISOString().slice(0, 10);
  return createJournalEntryWithLines(db, date, desc, lines, 'venta', saleId, usuarioId);
}

module.exports = {
  ensureAccountingSchema,
  ensureAccount,
  ensureDefaultAccounts,
  existingEntryForOrigin,
  createJournalEntryWithLines,
  autoEntryForCashClose,
  autoEntryForPurchase,
  autoEntryForSale
};
